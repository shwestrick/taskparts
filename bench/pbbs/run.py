#!/usr/bin/env python3
# Generates inputs, then sweeps the number of workers for each benchmark
# and scheduler, appending one row per timed round to WORK/results.csv.
# Rows already in the CSV are skipped, so an interrupted sweep resumes.
#
# usage: run.py WORK_DIR [--procs 1-10] [--rounds 5] [--only bench ...]
#                        [--check-procs 10] [--prepare-only]

import argparse
import csv
import os
import subprocess
import sys
import tempfile
import time

from common import BENCHMARKS, VARIANTS, binary, env_for, test_inputs

# PBBS's makefiles pass -mcx16, which is x86 only
MAKE_VARS = ["CC=clang++", "CCFLAGS=-O2 -std=c++17 -DNDEBUG -I . -w"]


def impl_dir(work, b):
    return os.path.join(work, "pbbsbench", "benchmarks", b)


def first_test(work, b):
    _, check, data_dir, tests = test_inputs(work, b)
    _, inputs, run_opts, check_opts = tests[0]
    if isinstance(inputs, str):
        inputs = [inputs]
    return check, data_dir, inputs, run_opts, check_opts


def prepare(work, benches):
    # some inputs are generated by running a benchmark (e.g., delaunayRefine's
    # by the stock delaunay), so give each benchmark its stock binary name
    for b in BENCHMARKS:
        stock = binary(work, b, "parlay")[:-len(".parlay")]
        if not os.path.exists(stock):
            os.symlink(os.path.basename(binary(work, b, "parlay")), stock)
    for b in benches:
        check, data_dir, inputs, _, _ = first_test(work, b)
        d = impl_dir(work, b)
        print(f"preparing {b}: {' '.join(inputs)}", flush=True)
        subprocess.run(["make", "-s"] + MAKE_VARS + inputs,
                       cwd=os.path.join(d, data_dir), check=True)
        subprocess.run(["make", "-s"] + MAKE_VARS + [os.path.basename(check)],
                       cwd=os.path.join(d, os.path.dirname(check)), check=True)


def run_once(work, b, variant, p, rounds, check):
    checker, data_dir, inputs, run_opts, check_opts = first_test(work, b)
    d = impl_dir(work, b)
    ins = [os.path.join(data_dir, i) for i in inputs]
    out = tempfile.mktemp(prefix="pbbs_out_")
    cmd = [binary(work, b, variant)] + run_opts.split() + ["-r", str(rounds), "-o", out] + ins
    r = subprocess.run(cmd, cwd=d, env=env_for(variant, p), capture_output=True,
                       text=True, timeout=900)
    if r.returncode != 0:
        raise RuntimeError(f"{' '.join(cmd)} exited with {r.returncode}\n{r.stdout}{r.stderr}")
    times = [float(l.split(":")[1]) for l in r.stdout.splitlines()
             if l.startswith("Parlay time:")]
    if len(times) != rounds:
        raise RuntimeError(f"unexpected output from {' '.join(cmd)}\n{r.stdout}{r.stderr}")
    ok = ""
    if check:
        c = subprocess.run([checker] + check_opts.split() + ins + [out], cwd=d,
                           capture_output=True, text=True)
        bad = [l for l in c.stdout.splitlines() if l and not l.startswith(":")]
        ok = "fail" if (c.returncode != 0 or bad) else "pass"
        if ok == "fail":
            print(f"  CHECK FAILED: {b} [{variant}] P={p}\n{c.stdout}{c.stderr}", flush=True)
    if os.path.exists(out):
        os.remove(out)
    return times, ok


def parse_procs(s):
    if "-" in s:
        lo, hi = s.split("-")
        return list(range(int(lo), int(hi) + 1))
    return [int(x) for x in s.split(",")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("work")
    ap.add_argument("--procs", default="1-10")
    ap.add_argument("--rounds", type=int, default=5)
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--check-procs", default="10")
    ap.add_argument("--prepare-only", action="store_true")
    ap.add_argument("--out", default=None)
    ap.add_argument("--variants", nargs="*", default=VARIANTS)
    args = ap.parse_args()
    work = os.path.abspath(args.work)
    benches = args.only or BENCHMARKS
    prepare(work, benches)
    if args.prepare_only:
        return
    procs = parse_procs(args.procs)
    check_procs = set(parse_procs(args.check_procs)) if args.check_procs else set()
    path = args.out or os.path.join(work, "results.csv")
    done = set()
    if os.path.exists(path):
        with open(path) as f:
            for row in csv.DictReader(f):
                done.add((row["benchmark"], row["variant"], int(row["procs"])))
    new = not os.path.exists(path)
    with open(path, "a", newline="") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["benchmark", "variant", "procs", "round", "seconds", "check"])
        # descending P first, so that the cheap runs give an early picture;
        # variants interleaved, so that drift over time affects them alike
        for p in sorted(procs, reverse=True):
            for b in benches:
                for v in args.variants:
                    if (b, v, p) in done:
                        continue
                    t0 = time.time()
                    try:
                        times, ok = run_once(work, b, v, p, args.rounds, p in check_procs)
                    except Exception as e:
                        print(f"  ERROR: {b} [{v}] P={p}: {e}", flush=True)
                        w.writerow([b, v, p, -1, "nan", "error"])
                        f.flush()
                        continue
                    for i, t in enumerate(times):
                        w.writerow([b, v, p, i, t, ok])
                    f.flush()
                    med = sorted(times)[len(times) // 2]
                    print(f"P={p:2} {b:45} {v:18} median {med:.4f}s "
                          f"{ok} ({time.time() - t0:.0f}s wall)", flush=True)


if __name__ == "__main__":
    main()
